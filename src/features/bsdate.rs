pub const FIRST_YEAR: i32 = 2000;
#[cfg(test)]
pub const LAST_YEAR: i32 = 2100;

pub const MONTHS_EN: [&str; 12] = [
    "Baisakh", "Jestha", "Asar", "Shrawan", "Bhadra", "Asoj", "Kartik", "Mangsir", "Poush", "Magh",
    "Falgun", "Chaitra",
];
pub const MONTHS_NE: [&str; 12] = [
    "बैशाख",
    "जेठ",
    "असार",
    "साउन",
    "भदौ",
    "असोज",
    "कार्तिक",
    "मंसिर",
    "पुष",
    "माघ",
    "फागुन",
    "चैत",
];

fn table() -> &'static Vec<[u8; 12]> {
    static T: OnceLock<Vec<[u8; 12]>> = OnceLock::new();
    T.get_or_init(|| {
        TABLE
            .lines()
            .map(|l| {
                let (_, rest) = l.split_once(':').unwrap_or(("", ""));
                let mut a = [30u8; 12];
                for (i, v) in rest.split(',').enumerate().take(12) {
                    a[i] = v.trim().parse().unwrap_or(30);
                }
                a
            })
            .collect()
    })
}

/// Day number (days since 1970-01-01) of BS 2000-01-01 = AD 1943-04-14.
fn epoch() -> i64 {
    days_from_civil(1943, 4, 14)
}

#[cfg(test)]
pub fn days_in_month(y: i32, m: u32) -> Option<u32> {
    let row = table().get((y - FIRST_YEAR) as usize)?;
    row.get(m as usize - 1).map(|d| *d as u32)
}

/// AD day number → (BS year, month 1–12, day).
pub fn from_day_number(dn: i64) -> Option<(i32, u32, u32)> {
    let mut left = dn - epoch();
    if left < 0 {
        return None;
    }
    for (yi, row) in table().iter().enumerate() {
        let ylen: i64 = row.iter().map(|d| *d as i64).sum();
        if left >= ylen {
            left -= ylen;
            continue;
        }
        for (mi, d) in row.iter().enumerate() {
            if left < *d as i64 {
                return Some((FIRST_YEAR + yi as i32, mi as u32 + 1, left as u32 + 1));
            }
            left -= *d as i64;
        }
    }
    None
}

/// BS date → AD day number.
#[cfg(test)]
pub fn to_day_number(y: i32, m: u32, d: u32) -> Option<i64> {
    if !(FIRST_YEAR..=LAST_YEAR).contains(&y)
        || !(1..=12).contains(&m)
        || d == 0
        || d > days_in_month(y, m)?
    {
        return None;
    }
    let t = table();
    let mut n = epoch();
    for row in &t[..(y - FIRST_YEAR) as usize] {
        n += row.iter().map(|x| *x as i64).sum::<i64>();
    }
    let row = &t[(y - FIRST_YEAR) as usize];
    n += row[..m as usize - 1].iter().map(|x| *x as i64).sum::<i64>();
    Some(n + d as i64 - 1)
}

pub fn nepali_digits(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_ascii_digit() {
                char::from_u32('०' as u32 + (c as u32 - '0' as u32)).unwrap_or(c)
            } else {
                c
            }
        })
        .collect()
}

/// "7 Mangsir 2083" or "७ मंसिर २०८३".
pub fn format(dn: i64, nepali: bool) -> Option<String> {
    let (y, m, d) = from_day_number(dn)?;
    Some(if nepali {
        nepali_digits(&format!("{d} {} {y}", MONTHS_NE[m as usize - 1]))
    } else {
        format!("{d} {} {y}", MONTHS_EN[m as usize - 1])
    })
}

/// User-editable holidays: holidays.json = [{"bs":"2083-01-01","name":"New Year"}].
#[derive(serde::Deserialize, serde::Serialize, Clone, Debug, PartialEq)]
pub struct Holiday {
    pub bs: String,
    pub name: String,
}

pub fn holidays() -> Vec<Holiday> {
    crate::util::load_json::<Vec<Holiday>>("holidays.json")
}

pub fn holiday_on(dn: i64, list: &[Holiday]) -> Option<String> {
    let (y, m, d) = from_day_number(dn)?;
    let key = format!("{y:04}-{m:02}-{d:02}");
    list.iter().find(|h| h.bs == key).map(|h| h.name.clone())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn table_complete() {
        assert_eq!(table().len(), 101);
        for (i, row) in table().iter().enumerate() {
            let s: u32 = row.iter().map(|d| *d as u32).sum();
            // years after 2090 are published projections (one source only)
            let ok = if i <= 90 {
                (365..=366).contains(&s)
            } else {
                (364..=367).contains(&s)
            };
            assert!(ok, "year {} sums {s}", 2000 + i);
        }
    }
    #[test]
    fn known_new_years() {
        assert_eq!(
            from_day_number(days_from_civil(1943, 4, 14)),
            Some((2000, 1, 1))
        );
        assert_eq!(
            from_day_number(days_from_civil(2023, 4, 14)),
            Some((2080, 1, 1))
        );
        assert_eq!(
            from_day_number(days_from_civil(2024, 4, 13)),
            Some((2081, 1, 1))
        );
    }
    #[test]
    fn roundtrip() {
        for dn in (days_from_civil(1950, 1, 1)..days_from_civil(2040, 1, 1)).step_by(37) {
            let (y, m, d) = from_day_number(dn).unwrap();
            assert_eq!(to_day_number(y, m, d), Some(dn));
        }
    }
    #[test]
    fn digits() {
        assert_eq!(nepali_digits("2083"), "२०८३");
    }
}
